#!/usr/bin/env node
// Generates the feature registry the pages read (src/features/index.js, not committed).
//
//   node scripts/build-features.mjs [--root <dir>]
//
// Every src/features/<id>/index.js is computed on the current state inside the isolation of lib/sandbox.js
// (empty environment, read-only copy, no network, time limit): the site never imports the code of a feature, it
// only receives the data it returned. A feature that does not load, breaks the contract, throws or hangs is
// skipped with a warning and never stops the build.

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { evaluateFeatures, SandboxUnavailable } from '../lib/sandbox.js'
import { cargarEstado } from '../lib/estado-node.js'

export async function buildFeatures(root, options = {}) {
  const result = await evaluateFeatures(root, cargarEstado(root), options)
  const header = '// Generated by scripts/build-features.mjs from src/features/*/index.js. Do not edit; it is not committed.\n'
  writeFileSync(join(root, 'src/features/index.js'), `${header}export default ${JSON.stringify(result.features, null, 2)}\n`)
  return result
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rootFlag = process.argv.indexOf('--root')
  const root = rootFlag === -1 ? fileURLToPath(new URL('..', import.meta.url)) : process.argv[rootFlag + 1]
  // A Node without the network switch refuses to run any feature: say so once, in plain words, and fail the build.
  const { features, omitidas } = await buildFeatures(root).catch((error) => {
    if (!(error instanceof SandboxUnavailable)) throw error
    console.error(`No se pueden construir las features: ${error.message}`)
    process.exit(1)
  })
  for (const { id, motivo } of omitidas) console.log(`⚠ feature ${id} omitida: ${motivo}`)
  console.log(`Features: ${features.length} en la web${omitidas.length ? `, ${omitidas.length} omitida(s)` : ''}.`)
}
